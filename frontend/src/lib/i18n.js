const DICTIONARIES = { en: en, hi: hi };

// current language, kept here so plain functions (like deadline text) can use it too
let current = "en";

export function setCurrentLang(lang) {
  current = lang === "hi" ? "hi" : "en";
}

export function getCurrentLang() {
  return current;
}

export function t(key, vars) {
  let text = DICTIONARIES[current][key];
  if (text === undefined) text = en[key];
  if (text === undefined) return key;

  if (vars) {
    for (const name in vars) {
      text = text.split("{" + name + "}").join(vars[name]);
    }
  }
  return text;
}

// date words follow the language, digits stay 0-9
export function dateLocale() {
  return current === "hi" ? "hi-IN" : "en-IN";
}
